function drawSnail(canvas, pose = "normal") {
  const rows = SNAIL[pose], ctx = canvas.getContext("2d");
  canvas.width = rows[0].length; canvas.height = rows.length;
  ctx.imageSmoothingEnabled = false; ctx.clearRect(0, 0, canvas.width, canvas.height);
  rows.forEach((row, y) => [...row].forEach((ch, x) => {
    if (ch === ".") return;
    ctx.fillStyle = SNAIL_PALETTE[ch]; ctx.fillRect(x, y, 1, 1);
  }));
}
globalThis.SNAIL = SNAIL; globalThis.SNAIL_PALETTE = SNAIL_PALETTE; globalThis.drawSnail = drawSnail;
