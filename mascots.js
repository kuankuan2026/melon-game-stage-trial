function drawMascot(canvas, name) {
  const rows = MASCOTS[name], ctx = canvas.getContext("2d");
  canvas.width = rows[0].length; canvas.height = rows.length;
  ctx.imageSmoothingEnabled = false; ctx.clearRect(0, 0, canvas.width, canvas.height);
  rows.forEach((row, y) => [...row].forEach((ch, x) => {
    if (ch === ".") return;
    ctx.fillStyle = MASCOT_PALETTE[ch]; ctx.fillRect(x, y, 1, 1);
  }));
}
globalThis.MASCOTS = MASCOTS; globalThis.MASCOT_PALETTE = MASCOT_PALETTE; globalThis.drawMascot = drawMascot;
